    static func drawLogo(at origin: NSPoint) {
        drawPixels(logo, at: origin, alpha: 1)
    }

    static func draw(food: Bool, halves: Int, at origin: NSPoint, unknown: Bool) {
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current?.shouldAntialias = false
        defer { NSGraphicsContext.restoreGraphicsState() }
        for (x, y, original) in food ? foodPixels : heart {
            let empty = halves == 0 || (halves == 1 && x >= 8)
            let rgb: UInt32 = empty ? (original == 0x321B24 ? 0x626271 : 0x292934) : original
            drawPixel(rgb, x: x, y: y, at: origin, alpha: unknown ? 0.35 : 1)
        }
    }

    private static func drawPixels(_ pixels: [(Int, Int, UInt32)], at origin: NSPoint, alpha: CGFloat) {
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current?.shouldAntialias = false
        defer { NSGraphicsContext.restoreGraphicsState() }
        for (x, y, rgb) in pixels { drawPixel(rgb, x: x, y: y, at: origin, alpha: alpha) }
    }

    private static func drawPixel(_ rgb: UInt32, x: Int, y: Int, at origin: NSPoint, alpha: CGFloat) {
        NSColor(calibratedRed: CGFloat((rgb >> 16) & 255) / 255,
                green: CGFloat((rgb >> 8) & 255) / 255,
                blue: CGFloat(rgb & 255) / 255,
                alpha: alpha).setFill()
        NSRect(x: origin.x + CGFloat(x), y: origin.y + CGFloat(y), width: 1, height: 1).fill()
    }
